export function PrivacyPage() {
  const locale = usePageLocale();
  const copy = privacyCopy[locale];
  const page = staticPages.privacy;
  const brandLabel = t(locale, brandName);
  const path = pagePath(locale, "privacy");

  return (
    <>
      <Seo
        locale={locale}
        title={`${t(locale, page.title)} | ${brandLabel}`}
        description={t(locale, page.description)}
        path={path}
        structuredData={[
          createOrganizationSchema(),
          createBreadcrumbSchema([
            { name: locale === "ru" ? "Главная" : "Գլխավոր", path: `/${locale}/` },
            { name: t(locale, page.title), path },
          ]),
        ]}
      />

      <section className="legal-page">
        <div className="legal-page__inner">
          <div className="legal-page__hero">
            <p className="legal-page__eyebrow">{copy.eyebrow}</p>
            <h1>{t(locale, page.title)}</h1>
            <p className="legal-page__effective">{copy.effective}</p>
            <p className="legal-page__lead">{copy.lead}</p>
          </div>

          <div className="legal-page__sections">
            {copy.sections.map((section) => (
              <section className="legal-page__section" key={section.title}>
                <h2>{section.title}</h2>
                {section.body ? <p>{section.body}</p> : null}
                <ul>
                  {section.items.map((item) => (
                    <li key={item}>{item}</li>
                  ))}
                </ul>
              </section>
            ))}

            <section className="legal-page__section legal-page__section--contacts">
              <h2>{copy.contactsTitle}</h2>
              <dl>
                {copy.contacts.map((item) => (
                  <div key={item.label}>
                    <dt>{item.label}</dt>
                    <dd>
                      {item.value === phone ? <a href={phoneHref}>{item.value}</a> : item.value}
                    </dd>
                  </div>
                ))}
              </dl>
            </section>
          </div>

          <Link className="legal-page__back" to={`/${locale}/`}>
            {copy.backHome}
          </Link>
        </div>
      </section>
    </>
  );
}
